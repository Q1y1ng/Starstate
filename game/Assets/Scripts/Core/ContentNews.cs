    /// <summary>新闻条目（纯数据，按日期可见：date <= 当前游戏日期）。</summary>
    public class NewsItem
    {
        public string date;     // ISO "yyyy-MM-dd"
        public string cat;      // 国际 / 国内 / 本地
        public string title;
        public string body;
    }

    /// <summary>新闻注册表：ContentNews.Register() 灌入，Ui 按 GameState.date 过滤读取（不入存档）。</summary>
    public static class News
    {
        public static readonly List<NewsItem> All = new List<NewsItem>();

        public static void Add(string date, string cat, string title, string body)
        {
            All.Add(new NewsItem { date = date, cat = cat, title = title, body = body });
        }

        /// <summary>返回当前可见新闻（新→旧），catFilter 为 null 时不过滤。</summary>
        public static List<NewsItem> Visible(string isoDate, string catFilter, int max)
        {
            var pool = new List<NewsItem>();
            foreach (var n in All)
            {
                if (string.CompareOrdinal(n.date, isoDate) > 0) continue;
                if (catFilter != null && catFilter.Length > 0 && n.cat != catFilter) continue;
                pool.Add(n);
            }
            pool.Sort((a, b) => string.CompareOrdinal(b.date, a.date));
            if (pool.Count > max) pool.RemoveRange(max, pool.Count - max);
            return pool;
        }
    }

