        /// <summary>
        /// 状态感知开场白：两把尺、路线、程序违规记录、同批进度、家庭压力优先于常规台词。
        /// 返回 null = 没有特别的话，走基础池。
        /// </summary>
        public static string StateLine(GameState st, string npcId)
        {
            if (st == null || string.IsNullOrEmpty(npcId)) return null;

            switch (npcId)
            {
                case "shenyan":
                    if (st.HasMark("has_violation"))
                        return "沈砚把一份台账复印件推过来，没抬头：“你最近签的件，有三份我标了记号。不是坏事——标了记号，说明我在看着。”";
                    if (st.compliance >= 80)
                        return "沈砚难得倒了杯水：“全市的合规记录我看过。你的退件率最高——退件不是问题，是答案。”";
                    if (st.compliance < 50)
                        return "沈砚看着窗外：“你这两个月的件，签得有点快。”——他只说了“快”，别的都留在了“快”后面。";
                    break;

                case "shao":
                    if (st.efficiency < 45)
                        return "邵志远把进度表拍在桌上：“三季度指标全省倒数第三。你守程序我认，可进度也得有人守。”";
                    if (st.efficiency >= 70)
                        return "邵志远笑了：“省里现场会定在大同。你的进度表，终于能上墙了。”";
                    break;

                case "cen":
                    if (st.HasMark("pb_1_private"))
                        return "岑伯衡抬了抬下巴：“基金那件事，办得像个市长——风险是自己算清楚的，不是别人替你砍的。”";
                    if (st.route == "uplink")
                        return "岑伯衡看着窗外：“向上争取不是要钱，是要说法。你最近的说法，省里听进去了几句。”";
                    if (st.route == "people")
                        return "岑伯衡：“民生的事见效慢。慢的事，最考验坐不住的时候。”";
                    if (st.route == "project")
                        return "岑伯衡：“项目是我的老本行。你这几年的开工率，我看过——数字不虚。”";
                    break;

                case "han":
                    if (Career.GradeYears(st) >= 4)
                        return "韩清把履历推过来：“满届还有一年。这一年最不值钱，也最要命——很多人的档案，就是在最后一年花了。”";
                    if (st.HasMark("rival_1_done"))
                        return "韩清收起表格：“同批已经有人上去了。这对你是压力，也是材料——‘在竞争中保持稳定’，组织上认这句话。”";
                    break;

                case "fang":
                    if (st.compliance < 60)
                        return "方启年抱着账本站在门口没进来：“市长，有几笔先签后补的，我按您的要求都留了痕。”";
                    break;

                case "linwan":
                    if (st.player.stress >= 70)
                        return "林晚把汤放在桌上，看了你一眼：“你这两个月的白头发，比去年一年都多。”";
                    if (st.resigned || st.phase == Phase.Ending)
                        return "林晚在收拾东西：“去哪儿都行。别再把家当成办公室就行。”";
                    break;

                case "xu":
                    if (st.grade != null && st.grade.StartsWith("六品"))
                        return "许飞的电话：“听说你也上来了。”他顿了两秒，“那下回见面，就是平级了。”";
                    if (st.HasMark("rival_grace"))
                        return "许飞：“上回你那四个字，我记着。”他没说记着什么，但语气比上次软。";
                    if (st.HasMark("rival_probe"))
                        return "许飞接起电话先笑了笑：“上回打听门路的事，我就当没听见。下不为例。”";
                    break;

                case "zhoujin":
                    if (st.pendingDossierIds != null && st.pendingDossierIds.Count >= 4)
                        return "周谨把卷宗包放下，没走：“老板，案头压了四五件。压着的件不会自己变少，只会自己变急。”";
                    break;

                case "rensheng":
                    if (st.HasMark("idle_enforce"))
                        return "任慎站着没坐：“收回来的那宗地重新挂牌成交了，价高了两成。有些人开始说，大同不好说话了。”";
                    break;

                case "laokang":
                    if (st.underInvestigation)
                        return "老康的信只有一行字：“早该在第一次不该签的时候，就不签。”";
                    break;
            }
            return null;
        }

        /// <summary>无 AI 时的回退交谈：状态台词优先，否则按日期轮换；选项随熟悉度/信任解锁。</summary>
        public static NpcTalkDto FallbackTalk(GameState st, string npcId)
        {
            string[] pool;
            if (!Lines.TryGetValue(npcId, out pool) || pool == null || pool.Length == 0)
                pool = new[] { "（你们在走廊点了点头，各自忙去了。）" };
            var d = GameClock.Parse(st.date);
            string line = StateLine(st, npcId);
            if (string.IsNullOrEmpty(line))
                line = pool[(d.DayOfYear + npcId.Length) % pool.Length];

            if (IsStanding(npcId))
            {
                var r = st.relations.Find(x => x.id == npcId);
                int fam = r != null ? r.familiar : 0;
                int trust = r != null ? r.trust : 0;

                var opts = new List<TalkOptionDto>
                {
                    new TalkOptionDto
                    {
                        label = "就本周卷宗请教一句",
                        mood = "warm",
                        reply = "对方沉吟两秒：“先把附件看完，再签字。别的，你自己掂量。”",
                    },
                    new TalkOptionDto
                    {
                        label = "只寒暄，不谈公事",
                        mood = "neutral",
                        reply = "“好。”——在这栋楼里，不谈公事也是一种态度。",
                    },
                    new TalkOptionDto
                    {
                        label = "起身告辞",
                        mood = "distant",
                        reply = "“忙去吧。”门关上的声音很轻。",
                    },
                };

                // 信任到一定程度，才有人肯说一句公事之外的话
                if (trust >= 25)
                    opts.Insert(1, new TalkOptionDto
                    {
                        label = "把心里的一件事说给他听",
                        mood = "warm",
                        reply = "他听完没评价，只说了一句：“这事你别再跟第二个人说。”——在这栋楼里，这句话比承诺重。",
                    });

                // 熟悉到一定程度，才敢把材料交出去让别人先看一眼
                if (fam >= 50)
                    opts.Insert(opts.Count - 1, new TalkOptionDto
                    {
                        label = "请他帮你把关一份材料",
                        mood = "warm",
                        reply = "他翻得很快，在第三页停住了：“这里少一个出处。补上，别让人问。”",
                    });

                return new NpcTalkDto { greeting = line, lines = new string[0], options = opts.ToArray() };
            }

            return new NpcTalkDto
            {
                greeting = line,
                lines = new string[0],
                options = new[]
                {
                    new TalkOptionDto { label = "顺着话头聊聊", mood = "warm", reply = "你们又聊了几句，比刚才更近了一步。" },
                    new TalkOptionDto { label = "先去忙了", mood = "neutral", reply = "“行，忙去吧。”——机关的一天，寒暄也是工作。" },
                },
            };
        }

        static bool IsStanding(string id)
        {
            return id == "cen" || id == "han" || id == "shenyan" || id == "shao" || id == "zhoujin"
                || id == "laokang" || id == "fang" || id == "rensheng" || id == "xu" || id == "linwan";
        }
    }
