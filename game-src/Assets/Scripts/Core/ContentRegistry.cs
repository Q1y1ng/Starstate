        /// <summary>月末“本月城市面”文案（按年，季度月出现）。</summary>
        public static readonly Func<string, string> MonthFlavor = key =>
        {
            if (string.IsNullOrEmpty(key) || key.Length < 4) return "";
            if (!int.TryParse(key.Substring(0, 4), out int year)) return "";
            int month = key.Length >= 7 && int.TryParse(key.Substring(5, 2), out int m) ? m : 0;
            if (month % 3 != 0) return "";
            return Years.ContainsKey(year) ? Years[year].social : "";
        };

